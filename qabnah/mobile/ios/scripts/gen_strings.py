def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_strings(path, table, idx, header):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"/* {header} — generated; keep en and ar in sync. */\n\n")
        for k in sorted(table):
            f.write(f'"{k}" = "{esc(table[k][idx])}";\n')


def used_keys(dirs):
    keys = set()
    for d in dirs:
        for path in glob.glob(os.path.join(ROOT, d, "**", "*.swift"), recursive=True):
            src = open(path, encoding="utf-8").read()
            # literals inside lang.t( / lang.f( / t( / f( calls (up to the closing paren of a simple call)
            for m in re.finditer(r'(?:\blang\.|\b)(?:t|f)\(([^()]*(?:\([^()]*\)[^()]*)*)\)', src):
                for lit in re.findall(r'"([a-z_0-9]+(?:\.[a-z_0-9]+)+)"', m.group(1)):
                    keys.add(lit)
            # explicit key-literal params (subtitleKey:, key:, stage strings)
            for lit in re.findall(r'(?:subtitleKey|key): "([a-z_0-9.]+)"', src):
                keys.add(lit)
            for lit in re.findall(r'stage = "([a-z_0-9.]+)"', src):
                keys.add(lit)
    return keys



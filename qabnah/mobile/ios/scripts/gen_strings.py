def main():
    apps = {
        "QabnahConsumer": ({**COMMON, **CONSUMER}, ["SharedUI", "QabnahConsumer"], "consumer"),
        "QabnahCaptain": ({**COMMON, **CAPTAIN}, ["SharedUI", "QabnahCaptain"], "captain"),
    }
    ok = True
    for app, (table, dirs, kind) in apps.items():
        for lang, idx in (("en", 0), ("ar", 1)):
            write_strings(os.path.join(ROOT, app, "Resources", f"{lang}.lproj", "Localizable.strings"), table, idx,
                          f"{app} {lang}")
            write_strings(os.path.join(ROOT, app, "Resources", f"{lang}.lproj", "InfoPlist.strings"),
                          INFOPLIST[kind], idx, f"{app} Info.plist {lang}")
        missing = sorted(k for k in used_keys(dirs) | DYNAMIC[kind] if k not in table)
        # SharedUI keys only used by the other app are fine when absent.
        print(f"{app}: {len(table)} keys; missing referenced keys: {missing}")
        if missing:
            ok = False
    return 0 if ok else 1


